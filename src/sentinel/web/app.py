"""HTTP API and page host.

One process that can be deployed and left running: JSON endpoints over the warehouse,
the generated pages, and a single crawl endpoint that uses the browser backend when it
is installed.

Deliberately small. The dashboard is still generated by `sentinel dashboard`; this app
serves it and answers questions about the data behind it.
"""

from datetime import date
from pathlib import Path

from sentinel.warehouse import db

INSTALL_HINT = 'the web extra is not installed: pip install "sentinel[web]"'


def create_app(con, paths):
    """con may be a connection or a zero-argument callable returning one.

    A long-lived read-write connection holds DuckDB's exclusive lock for the life of the
    server, which blocks `sentinel watch` from writing while the web app is running. The
    server therefore opens a read-only connection per request; a caller that passes a
    connection (the tests) keeps the simple behaviour.
    """
    """Build the app. FastAPI is imported here, not at module scope, so that importing
    every module of this package works on a machine that only installed the core deps."""
    try:
        from fastapi import FastAPI, HTTPException
        from fastapi.responses import FileResponse, HTMLResponse
        from pydantic import BaseModel
    except ImportError as exc:  # pragma: no cover - exercised only without the extra
        raise ImportError(INSTALL_HINT) from exc

    class CrawlRequest(BaseModel):
        url: str
        markdown: bool = True

    from contextlib import contextmanager

    @contextmanager
    def db_session(write: bool = False):
        # Reads use the read-only factory so the server never holds the write lock.
        # A write needs a read-write connection, which cannot coexist with a reader, so
        # it is opened only for the statement and may fail with contention - which the
        # POST handler turns into a 503 rather than a 500.
        if callable(con):
            connection = db.connect(paths.db) if write else con()
            try:
                yield connection
            finally:
                connection.close()
        else:
            yield con

    with db_session() as conn:
        from sentinel import jobs as _jobs
        _jobs.reconcile_stale(conn)  # never leave a spinner for a dead worker

    app = FastAPI(title="SENTINEL", version="0.1.0", description="Point-in-time public-company intelligence")

    @app.get("/api/health")
    def health() -> dict:
        with db_session() as conn:
            counts = db.table_counts(conn)
        return {"status": "ok", "companies": counts.get("dim_company", 0),
                "facts": counts.get("fact_xbrl", 0), "findings": counts.get("finding", 0)}

    @app.get("/api/companies")
    def companies(q: str = "", limit: int = 25) -> list[dict]:
        sql = ("SELECT cik, name, tickers, sic, status FROM dim_company "
               "WHERE (? = '' OR lower(name) LIKE ? OR upper(tickers) LIKE ?) "
               "ORDER BY name LIMIT ?")
        like = "%" + q.lower() + "%"
        with db_session() as conn:
            frame = db.query(conn, sql, [q, like, "%" + q.upper() + "%", min(limit, 200)])
        return frame.to_dict("records")

    @app.get("/api/company/{cik}")
    def company(cik: int) -> dict:
        with db_session() as conn:
            rows = db.query(conn, "SELECT * FROM dim_company WHERE cik = ?", [cik])
            if rows.empty:
                raise HTTPException(404, "unknown cik")
            metrics = db.query(conn, """
                SELECT metric_id, fiscal_year, value, unit, tag_used, accession
                FROM fact_xbrl_canonical WHERE cik = ? AND fiscal_year >= 2015
                ORDER BY metric_id, fiscal_year DESC LIMIT 400
            """, [cik])
        return {"company": rows.iloc[0].to_dict(), "metrics": metrics.to_dict("records")}

    @app.get("/api/findings")
    def findings(grade: str = "", limit: int = 25) -> list[dict]:
        from sentinel.analytics import findings as ledger
        with db_session() as conn:
            frame = ledger.ledger(conn, grade=grade or None, limit=min(limit, 200))
        return frame.to_dict("records")

    @app.get("/api/digest")
    def digest(day: str = "") -> dict:
        from sentinel import watch
        with db_session() as conn:
            # a fresh warehouse has no watch_event table yet
            watch.ensure_schema(conn)
            target = date.fromisoformat(day) if day else (
                db.scalar(conn, "SELECT MAX(digest_date) FROM watch_event") or date.today())
            return watch.digest(conn, day=target)

    @app.post("/api/crawl")
    def crawl(request: CrawlRequest) -> dict:
        from sentinel.crawler import browser
        if not browser.available():
            raise HTTPException(503, browser.INSTALL_HINT)
        rendered = browser.render_sync(request.url)
        return {"url": rendered.url, "status": rendered.status, "ok": rendered.ok,
                "markdown_chars": len(rendered.markdown), "html_chars": len(rendered.html),
                "markdown": rendered.markdown if request.markdown else ""}

    class JobRequest(BaseModel):
        urls: list[str]
        label: str = ""

    @app.post("/api/jobs")
    def create_job(request: JobRequest):
        from sentinel import jobs

        from sentinel.jobs import UnsafeTarget

        urls = [u.strip() for u in request.urls if u.strip()]
        if not urls:
            raise HTTPException(400, "supply at least one http(s) URL")
        # A crawl endpoint on localhost is an SSRF primitive unless it refuses to be one.
        for url in urls:
            try:
                jobs.assert_safe_target(url)
            except UnsafeTarget as exc:
                raise HTTPException(400, str(exc))
        if len(urls) > jobs.MAX_URLS:
            raise HTTPException(400, f"at most {jobs.MAX_URLS} URLs per job")

        try:
            with db_session(write=True) as conn:
                job_id = jobs.create(conn, kind="url", target=request.label or urls[0], total=len(urls))
        except Exception as exc:
            # DuckDB permits one writer. A crawl job holding it must surface as "retry",
            # not as an opaque 500 that looks like a bug in the console.
            if "Cannot open file" in str(exc) or "being used by another process" in str(exc):
                raise HTTPException(503, "warehouse is busy: a crawl job is writing; retry shortly")
            raise

        # A worker runs it off the request thread when the app owns the database path.
        # Without one (tests) the job stays queued, which is the honest state.
        if callable(con):
            import threading

            from sentinel.config import Paths, identity, sources_config
            from sentinel.crawler.net import HttpFetcher

            def worker(job=job_id, batch=urls):
                connection = db.connect(paths.db)
                try:
                    _, defaults = sources_config()
                    root = Paths.build()
                    with HttpFetcher(root, identity(), defaults) as fetcher:
                        jobs.run(connection, root, fetcher, job, batch)
                finally:
                    connection.close()

            threading.Thread(target=worker, name="crawl-" + job_id, daemon=True).start()
        return {"job_id": job_id, "queued": len(urls)}

    @app.get("/api/jobs")
    def job_list(limit: int = 20):
        from sentinel import jobs
        with db_session() as conn:
            return jobs.listing(conn, max(1, min(limit, 100)))

    @app.get("/api/jobs/{job_id}")
    def job_detail(job_id: str):
        from sentinel import jobs
        with db_session() as conn:
            job = jobs.get(conn, job_id)
            if job is None:
                raise HTTPException(404, "unknown job")
            job["results"] = jobs.results(conn, job_id)
        return job

    @app.get("/api/jobs/{job_id}/bundle")
    def job_bundle(job_id: str):
        from sentinel import jobs
        with db_session() as conn:
            path = jobs.bundle(conn, paths, job_id)
        if path is None or not Path(path).exists():
            raise HTTPException(404, "nothing to download")
        return FileResponse(str(path), filename=Path(path).name)

    @app.get("/", response_class=HTMLResponse)
    def index() -> str:
        return (
            '<html><head><meta charset="utf-8"><title>SENTINEL</title>'
            '<style>body{background:#070a0e;color:#a8bccf;font:13px ui-monospace,monospace;padding:28px}'
            'a{color:#3ddc97;display:block;margin:6px 0}</style></head><body>'
            '<h1 style="font-size:13px;letter-spacing:.2em">SENTINEL API</h1>'
            '<a href="/dashboard.html">dashboard</a><a href="/crawler.html">crawler view</a>'
            '<a href="/provenance.html">provenance</a><a href="/api/health">/api/health</a>'
            '<a href="/docs">openapi docs</a></body></html>'
        )

    viz = Path(paths.root) / "viz"
    if viz.exists():
        for page in ("dashboard.html", "crawler.html", "provenance.html", "targets.html", "console.html",
                     "data.json", "targets.json", "crawler.png", "provenance.png"):
            target = viz / page
            if target.exists():
                app.add_api_route("/" + page, (lambda p=target: FileResponse(p)), methods=["GET"])
    return app
