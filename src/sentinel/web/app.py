"""HTTP API and page host.

One process that can be deployed and left running: JSON endpoints over the warehouse,
the generated pages, and a single crawl endpoint that uses the browser backend when it
is installed.

Deliberately small. The dashboard is still generated by `sentinel dashboard`; this app
serves it and answers questions about the data behind it.
"""

from datetime import date
from pathlib import Path

from sentinel.warehouse import db

INSTALL_HINT = 'the web extra is not installed: pip install "sentinel[web]"'


def create_app(con, paths):
    """Build the app. FastAPI is imported here, not at module scope, so that importing
    every module of this package works on a machine that only installed the core deps."""
    try:
        from fastapi import FastAPI, HTTPException
        from fastapi.responses import FileResponse, HTMLResponse
        from pydantic import BaseModel
    except ImportError as exc:  # pragma: no cover - exercised only without the extra
        raise ImportError(INSTALL_HINT) from exc

    class CrawlRequest(BaseModel):
        url: str
        markdown: bool = True

    app = FastAPI(title="SENTINEL", version="0.1.0", description="Point-in-time public-company intelligence")

    @app.get("/api/health")
    def health() -> dict:
        counts = db.table_counts(con)
        return {"status": "ok", "companies": counts.get("dim_company", 0),
                "facts": counts.get("fact_xbrl", 0), "findings": counts.get("finding", 0)}

    @app.get("/api/companies")
    def companies(q: str = "", limit: int = 25) -> list[dict]:
        sql = ("SELECT cik, name, tickers, sic, status FROM dim_company "
               "WHERE (? = '' OR lower(name) LIKE ? OR upper(tickers) LIKE ?) "
               "ORDER BY name LIMIT ?")
        like = "%" + q.lower() + "%"
        frame = db.query(con, sql, [q, like, "%" + q.upper() + "%", min(limit, 200)])
        return frame.to_dict("records")

    @app.get("/api/company/{cik}")
    def company(cik: int) -> dict:
        rows = db.query(con, "SELECT * FROM dim_company WHERE cik = ?", [cik])
        if rows.empty:
            raise HTTPException(404, "unknown cik")
        metrics = db.query(con, """
            SELECT metric_id, fiscal_year, value, unit, tag_used, accession
            FROM fact_xbrl_canonical WHERE cik = ? AND fiscal_year >= 2015
            ORDER BY metric_id, fiscal_year DESC LIMIT 400
        """, [cik])
        return {"company": rows.iloc[0].to_dict(), "metrics": metrics.to_dict("records")}

    @app.get("/api/findings")
    def findings(grade: str = "", limit: int = 25) -> list[dict]:
        from sentinel.analytics import findings as ledger
        frame = ledger.ledger(con, grade=grade or None, limit=min(limit, 200))
        return frame.to_dict("records")

    @app.get("/api/digest")
    def digest(day: str = "") -> dict:
        from sentinel import watch
        watch.ensure_schema(con)  # a fresh warehouse has no watch_event table yet
        target = date.fromisoformat(day) if day else (
            db.scalar(con, "SELECT MAX(digest_date) FROM watch_event") or date.today())
        return watch.digest(con, day=target)

    @app.post("/api/crawl")
    def crawl(request: CrawlRequest) -> dict:
        from sentinel.crawler import browser
        if not browser.available():
            raise HTTPException(503, browser.INSTALL_HINT)
        rendered = browser.render_sync(request.url)
        return {"url": rendered.url, "status": rendered.status, "ok": rendered.ok,
                "markdown_chars": len(rendered.markdown), "html_chars": len(rendered.html),
                "markdown": rendered.markdown if request.markdown else ""}

    @app.get("/", response_class=HTMLResponse)
    def index() -> str:
        return (
            '<html><head><meta charset="utf-8"><title>SENTINEL</title>'
            '<style>body{background:#070a0e;color:#a8bccf;font:13px ui-monospace,monospace;padding:28px}'
            'a{color:#3ddc97;display:block;margin:6px 0}</style></head><body>'
            '<h1 style="font-size:13px;letter-spacing:.2em">SENTINEL API</h1>'
            '<a href="/dashboard.html">dashboard</a><a href="/crawler.html">crawler view</a>'
            '<a href="/provenance.html">provenance</a><a href="/api/health">/api/health</a>'
            '<a href="/docs">openapi docs</a></body></html>'
        )

    viz = Path(paths.root) / "viz"
    if viz.exists():
        for page in ("dashboard.html", "crawler.html", "provenance.html", "data.json", "crawler.png", "provenance.png"):
            target = viz / page
            if target.exists():
                app.add_api_route("/" + page, (lambda p=target: FileResponse(p)), methods=["GET"])
    return app
